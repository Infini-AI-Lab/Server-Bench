"""Load the agent-facing specification. This module composes no prose.

Every prompt and instruction lives in the task, at
`serving_tasks/<TASK>/instruction.md`, generated by
`serving_tasks/_manage/instruction_render.py` from the frozen contract. The
harness reads that file and delivers it; it does not write, extend, wrap or
annotate it, and it holds no sentence an agent will read.

Run-specific facts travel as DATA, never as prose: `WORKSPACE.json` records
the run's identity, its stop condition and its deadline, and `./clock` reports
the remaining budget live.

`tests/contracts/test_the_instruction_only_states_facts.py` refuses advisory
shapes in the delivered document, for every task.
"""

from __future__ import annotations

from pathlib import Path

#: Workspace commands that a task specification may name.  The boot contract
#: checks only the commands named by this run's actual brief: standard tasks
#: receive ``version`` while instructed tasks receive ``checkpoint`` and
#: ``promote`` instead.
COMMANDS = (
    "clock",
    "gpu-clock",
    "serve.sh",
    "server.py",
    "version",
    "checkpoint",
    "promote",
    "measurements",
)

#: What `--stop` accepts. VALUES ONLY -- the meaning of each is the operator's
#: label on the evidence, and `WORKSPACE.json` carries the chosen one.
STOP_CONDITIONS = ("beat-all-baselines", "beat-one-baseline", "meet-slo",
                   "timebox")

#: The session headings whose bodies `agent.py` substitutes into when it
#: launches into an existing run. Kept OUT of the delivered document, which
#: the agent reads once at launch, and selected by name so a new kind of
#: session cannot silently fall back to another kind's words.
SESSION_HEADINGS = {
    "continuation": "## Continuation",
    "idle-restart": "## Idle restart",
    "cold-restart": "## Cold restart",
    "makeup": "## Make-up run",
}

#: Where the delivered document ends. Everything from here down is a session
#: prompt, not part of the specification.
FIRST_SESSION_HEADING = "## Continuation"


def instruction_path(task_dir: Path) -> Path:
    return Path(task_dir) / "instruction.md"


def _read(task_dir: Path) -> str:
    return instruction_path(task_dir).read_text("utf-8")


def _document(task_dir: Path) -> str:
    """The specification, without the session sections."""
    body = _read(task_dir)
    if FIRST_SESSION_HEADING not in body:
        raise RuntimeError(
            f"{instruction_path(task_dir)} has no session sections, so a "
            f"continued or restarted session has nothing to be told. Run "
            f"`taskctl render {Path(task_dir).name}`")
    return body.partition(FIRST_SESSION_HEADING)[0].rstrip() + "\n"


def _section(task_dir: Path, kind: str) -> str:
    """One session section's body, by name."""
    try:
        heading = SESSION_HEADINGS[kind]
    except KeyError:
        raise RuntimeError(
            f"no session section named {kind!r}; the task carries "
            f"{sorted(SESSION_HEADINGS)}") from None
    body = _read(task_dir)
    if heading not in body:
        raise RuntimeError(
            f"{instruction_path(task_dir)} has no `{heading}` section. Run "
            f"`taskctl render {Path(task_dir).name}`")
    after = body.partition(heading)[2]
    for other in SESSION_HEADINGS.values():
        if other != heading and other in after:
            after = after.partition(other)[0]
    return after.strip()


def build_brief(*, task_dir: Path, model_id: str, hours: float, carried: bool,
                stop: str = "timebox", workspace: Path | None = None) -> str:
    """The specification this task gives its agent, as delivered.

    Read, not composed. The arguments are the run's facts; the deadline and
    the stop rule are recorded in `WORKSPACE.json` by the workspace builder,
    and none of them changes a word of the document, which is why two runs of
    one task are briefed identically.
    """
    del model_id, hours, carried, stop, workspace       # recorded as data
    document = _document(Path(task_dir))
    leftover = [token for token in ("{budget_hours}", "{deadline_utc}")
                if token in document]
    if leftover:
        raise RuntimeError(
            f"{instruction_path(task_dir)} leaves {leftover} in the "
            f"specification itself; the agent would read a placeholder")
    return document


def session_prompt(task_dir: Path, *, kind: str, budget_seconds: float,
                   deadline_utc: str) -> str:
    """What a non-cold launch is told, in the task's own words.

    `kind` is one of `SESSION_HEADINGS`. Substitution only: the two numbers
    are this run's, every word is the task's.
    """
    return (_section(Path(task_dir), kind)
            .replace("{budget_hours}", f"{budget_seconds / 3600:.2f}")
            .replace("{deadline_utc}", str(deadline_utc)))


def executables_the_brief_names(workspace: Path) -> list[str]:
    """Executables the specification names, resolved from PATH.

    Distinct from `commands_missing_from`, which asks whether a workspace FILE
    exists. Both are needed and neither substitutes for the other: `version`
    is a file in the workspace, `aiperf` is a name on PATH, and a check that
    conflates them passes while half the document is unrunnable: a brief that
    says "aiperf is on your PATH" is checked against PATH, not against the
    workspace.
    """
    text = Path(workspace) / "AGENT_TASK.md"
    if not text.exists():
        return []
    body = text.read_text("utf-8")
    return [name for name in ("aiperf",) if name in body]


def commands_missing_from(workspace: Path) -> list[str]:
    """Which files the specification names are absent from the workspace."""
    workspace = Path(workspace)
    brief = workspace / "AGENT_TASK.md"
    if not brief.is_file():
        return []
    body = brief.read_text("utf-8")
    named = [command for command in COMMANDS if f"./{command}" in body]
    return [command for command in named if not (workspace / command).exists()]
